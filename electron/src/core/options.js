/** Fields whose values must come from a fixed list; anything else falls back to the group's defaults. */
const ENUMS = {
    'format.mode': MediaMode,
    'format.audioFormat': AudioFormat,
    'format.container': Container,
    'format.containerMethod': ContainerMethod,
    'format.codec': CodecPreference,
    'extras.sponsorBlock': SponsorBlockMode,
    'network.cookieBrowser': CookieBrowser,
    'output.overwrite': OverwriteRule,
}

export function defaultOptions() {
    const options = {}
    for (const [group, make] of Object.entries(GROUP_DEFAULTS)) options[group] = make()
    // Raw yt-dlp arguments, added after everything else.
    options.extraArguments = ''
    // Keeps the user's own yt-dlp config files from changing Purrloader's output and progress handling.
    options.ignoreConfig = true
    return options
}

function validField(path, value, fallback) {
    if (ENUMS[path]) return typeof value === 'string' && Object.hasOwn(ENUMS[path], value)
    if (path === 'format.maxHeight') return value === null || Number.isInteger(value)
    if (Array.isArray(fallback)) return Array.isArray(value) && value.every((item) => typeof item === 'string')
    if (typeof fallback === 'number') return Number.isInteger(value)
    return typeof value === typeof fallback
}

/** Missing or unreadable values fall back to their defaults, one group at a time, so settings saved by other
 * versions still load: saved keys win, missing ones keep their default, and an unreadable group is replaced by
 * defaults. */
export function decodeOptions(saved) {
    const options = defaultOptions()
    if (!saved || typeof saved !== 'object') return options
    for (const group of Object.keys(GROUP_DEFAULTS)) {
        const savedGroup = saved[group]
        if (!savedGroup || typeof savedGroup !== 'object' || Array.isArray(savedGroup)) continue
        const merged = { ...options[group] }
        let valid = true
        for (const [key, fallback] of Object.entries(options[group])) {
            if (!Object.hasOwn(savedGroup, key)) continue
            const value = savedGroup[key]
            if (!validField(`${group}.${key}`, value, fallback)) {
                valid = false
                break
            }
            merged[key] = Array.isArray(value) ? [...value] : value
        }
        if (valid) options[group] = merged
    }
    if (typeof saved.extraArguments === 'string') options.extraArguments = saved.extraArguments
    if (typeof saved.ignoreConfig === 'boolean') options.ignoreConfig = saved.ignoreConfig
    return options
}

export function cloneOptions(options) {
    return decodeOptions(JSON.parse(JSON.stringify(options)))
}

/** Cover art embedding fails the whole download for formats that can't hold it (WebM, WAV). */
export function supportsCoverArt(format) {
    return format.mode === 'audio' ? format.audioFormat !== 'wav' : ['mp4', 'mkv', 'mov'].includes(format.container)
}

export function supportsChapters(format) {
    return format.mode === 'audio' ? format.audioFormat !== 'wav' : format.container !== 'webm'
}

/** Extension the final file will most likely have; used for the file name preview. */
export function expectedExtension(format) {
    if (format.mode === 'audio') return format.audioFormat === 'best' ? 'm4a' : format.audioFormat
    return format.container === 'auto' ? 'mp4' : format.container
}

/** Reads or writes a dotted path like "format.maxHeight". */
export function getPath(object, path) {
    return path.split('.').reduce((value, key) => value?.[key], object)
}

export function setPath(object, path, value) {
    const keys = path.split('.')
    let target = object
    for (const key of keys.slice(0, -1)) target = target[key]
    target[keys.at(-1)] = value
}
